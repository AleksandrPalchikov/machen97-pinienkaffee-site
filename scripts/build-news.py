#!/usr/bin/env python3
"""Build the independent news section using Python's standard library."""
from datetime import datetime, timezone, timedelta
from email.utils import format_datetime
from html import escape
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET
import argparse
import editorial
import google_tags

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT
NEWS = OUTPUT / 'aktuelles'
PREVIEW = False
BASE = 'https://machen97.com'
MARKER = '<!-- Generated by scripts/build-news.py; edit content/articles/*.json. -->'
LABELS = {'news': 'Neuigkeiten', 'article': 'Artikel'}
AUTHOR = {'@type': 'Organization', '@id': BASE + '/#organization',
          'name': 'M97 Factory', 'url': BASE + '/#ueber-uns'}


def text(value):
    return escape(str(value), quote=True)


def url(post):
    return BASE + post.get('path', '/aktuelles/' + post['slug'] + '/')


def date_label(value):
    return datetime.fromisoformat(value).strftime('%d.%m.%Y')


def load_posts():
    posts, slugs = [], set()
    today = datetime.now(timezone(timedelta(hours=3)))
    for source in sorted((ROOT / 'content/articles').glob('*.json')):
        post = json.loads(source.read_text(encoding='utf-8'))
        if post.get('status') == 'draft':
            continue
        if post.get('status') != 'published':
            raise ValueError(f'{source.name}: status must be published or draft')
        slug = post['slug']
        if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', slug) or slug in slugs:
            raise ValueError(f'{source.name}: invalid or duplicate slug')
        slugs.add(slug)
        if post['category'] not in LABELS:
            raise ValueError(f'{source.name}: unknown category')
        for field in ['title', 'description', 'image_alt']:
            if not isinstance(post[field], str) or not post[field].strip():
                raise ValueError(f'{source.name}: {field} must contain text')
        published = datetime.fromisoformat(post['published'])
        modified = datetime.fromisoformat(post['modified'])
        if published.tzinfo is None or modified.tzinfo is None or modified < published:
            raise ValueError(f'{source.name}: invalid publication dates')
        if published > today:
            continue
        image = post['image']
        if not image.startswith('/images/') or '..' in image or not (ROOT / image.lstrip('/')).is_file():
            raise ValueError(f'{source.name}: image must exist in images/')
        if not post['intro'] or not post['sections']:
            raise ValueError(f'{source.name}: article body is empty')
        for section in post['sections']:
            if not section.get('heading') or not section.get('paragraphs'):
                raise ValueError(f'{source.name}: article section is empty')
            if 'link' in section:
                href = section['link']['href']
                if not href.startswith('/') or href.startswith('//'):
                    raise ValueError(f'{source.name}: links must stay on the website')
        posts.append(post)
    posts.extend(editorial.load(PREVIEW))
    paths = [url(post) for post in posts]
    if len(paths) != len(set(paths)):
        raise ValueError('Duplicate article URL')
    return sorted(posts, key=lambda post: (post.get('editorial', False), post['published'], post['slug']), reverse=True)


def article_schema(post):
    return {'@type': 'NewsArticle' if post['category'] == 'news' else 'BlogPosting',
            '@id': url(post) + '#article', 'url': url(post),
            'headline': post['title'], 'description': post['description'],
            'datePublished': post['published'], 'dateModified': post['modified'],
            'author': AUTHOR, 'publisher': AUTHOR,
            'image': [BASE + post['image']], 'inLanguage': 'de-DE',
            'mainEntityOfPage': {'@type': 'WebPage', '@id': url(post)},
            'articleSection': LABELS[post['category']]}


