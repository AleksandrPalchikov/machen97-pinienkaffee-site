def archive(posts):
    if any(post.get("editorial") for post in posts):
        return editorial.archive(posts, PREVIEW)
    cards = []
    for post in posts:
        cards.append(f'''<article class="post-card">
        <a class="post-cover" href="/aktuelles/{post['slug']}/" tabindex="-1" aria-hidden="true">
          <img src="{text(post['image'])}" alt="" width="720" height="480" loading="lazy" />
        </a>
        <div class="post-copy">
          <div class="post-meta"><span>{LABELS[post['category']]}</span><time datetime="{text(post['published'])}">{date_label(post['published'])}</time></div>
          <h2><a href="/aktuelles/{post['slug']}/">{text(post['title'])}</a></h2>
          <p>{text(post['description'])}</p>
          <a class="read-more" href="/aktuelles/{post['slug']}/" aria-label="{text('Beitrag lesen: ' + post['title'])}">Beitrag lesen <span aria-hidden="true">→</span></a>
        </div>
      </article>''')
    body = f'''<div class="archive-wrap">
    <div class="archive-heading">
      <span class="eyebrow">Das Journal von Pinienkaffee</span>
      <h1>Aktuelles &amp; Artikel</h1>
      <p>Neuigkeiten von M97 Factory.<br />Wissen und Inspiration rund um Pinienkaffee.</p>
    </div>
    <section class="post-grid" aria-label="Alle Beiträge">{''.join(cards) or '<p>Neue Beiträge folgen in Kürze.</p>'}</section>
  </div>'''
    graph = [{'@type': 'CollectionPage', '@id': BASE + '/aktuelles/#collection',
              'url': BASE + '/aktuelles/', 'name': 'Aktuelles & Artikel – Pinienkaffee',
              'description': 'Neuigkeiten und Artikel von Pinienkaffee und M97 Factory.',
              'inLanguage': 'de-DE', 'publisher': AUTHOR,
              'isPartOf': {'@id': BASE + '/#website'},
              'mainEntity': {'@type': 'ItemList', 'itemListElement': [
                  {'@type': 'ListItem', 'position': index + 1, 'url': url(post), 'name': post['title']}
                  for index, post in enumerate(posts)]}}]
    return layout('Aktuelles & Artikel', 'Neuigkeiten von M97 Factory und praktische Artikel rund um Pinienkaffee: Zubereitung, Produkte und Updates.', BASE + '/aktuelles/', graph, body)


def article(post):
    if post.get("editorial"):
        return editorial.render(post)
    paragraphs = ''.join(f'<p>{text(value)}</p>' for value in post['intro'])
    sections = []
    for section in post['sections']:
        section_body = ''.join(f'<p>{text(value)}</p>' for value in section['paragraphs'])
        if 'link' in section:
            section_body += f'<p><a href="{text(section["link"]["href"])}">{text(section["link"]["label"])} <span aria-hidden="true">→</span></a></p>'
        sections.append(f'<section><h2>{text(section["heading"])}</h2>{section_body}</section>')
    body = f'''<article class="article-wrap">
    <nav class="breadcrumbs" aria-label="Brotkrümelnavigation"><a href="/">Startseite</a><span aria-hidden="true">/</span><a href="/aktuelles/">Aktuelles</a></nav>
    <header class="article-heading">
      <span class="eyebrow">{LABELS[post['category']]}</span>
      <h1>{text(post['title'])}</h1>
      <p class="article-summary">{text(post['description'])}</p>
      <div class="byline"><span>M97 Factory · Machen97 UG</span><time datetime="{text(post['published'])}">{date_label(post['published'])}</time></div>
    </header>
    <figure class="article-image"><img src="{text(post['image'])}" alt="{text(post['image_alt'])}" width="1200" height="800" fetchpriority="high" /></figure>
    <div class="article-body">{paragraphs}{''.join(sections)}</div>
    <div class="article-end"><a href="/aktuelles/">← Alle Neuigkeiten und Artikel</a></div>
  </article>'''
    breadcrumb = {'@type': 'BreadcrumbList', 'itemListElement': [
        {'@type': 'ListItem', 'position': 1, 'name': 'Startseite', 'item': BASE + '/'},
        {'@type': 'ListItem', 'position': 2, 'name': 'Aktuelles', 'item': BASE + '/aktuelles/'},
        {'@type': 'ListItem', 'position': 3, 'name': post['title'], 'item': url(post)}]}
    return layout(post['title'], post['description'], url(post), [article_schema(post), breadcrumb], body, post['image'])


def xml_outputs(posts):
    namespace = 'http://www.sitemaps.org/schemas/sitemap/0.9'
    ET.register_namespace('', namespace)
    image_namespace = 'http://www.google.com/schemas/sitemap-image/1.1'
    ET.register_namespace('image', image_namespace)

    # Keep one canonical sitemap for search engines and AI crawlers. Only pages
    # that are intended to be indexed belong here; danke.html is explicitly
    # noindex because it is a form confirmation page.
    public_pages = []
    for page in sorted(OUTPUT.rglob('*.html')):
        relative = page.relative_to(OUTPUT)
        if any(part in {'.git', 'node_modules', '.venv', 'venv'} for part in relative.parts):
            continue
        html = page.read_text(encoding='utf-8')
        if re.search(r'<meta[^>]+name=["\']robots["\'][^>]+content=["\'][^"\']*noindex', html, re.I):
            continue
        if relative.name == 'index.html':
            path = '/' if relative.parent == Path('.') else '/' + relative.parent.as_posix().strip('/') + '/'
        else:
            path = '/' + relative.as_posix()
        canonical = re.search(r'<link[^>]+rel=["\']canonical["\'][^>]+href=["\']([^"\']+)', html, re.I)
        address = canonical.group(1) if canonical else BASE + path
        if address.startswith(BASE) and address not in {item[0] for item in public_pages}:
            public_pages.append((address, None, None))

    article_by_url = {url(post): post for post in posts}
    for index, (address, _, _) in enumerate(public_pages):
        post = article_by_url.get(address)
        public_pages[index] = (address, post.get('modified') if post else datetime.now(timezone.utc).date().isoformat(), post)

    full_sitemap = ET.Element('{' + namespace + '}urlset')
    for address, modified, post in sorted(public_pages):
        entry = ET.SubElement(full_sitemap, '{' + namespace + '}url')
        ET.SubElement(entry, '{' + namespace + '}loc').text = address
        ET.SubElement(entry, '{' + namespace + '}lastmod').text = modified
        if post and post.get('image'):
            image = ET.SubElement(entry, '{' + image_namespace + '}image')
            ET.SubElement(image, '{' + image_namespace + '}loc').text = BASE + post['image']
    ET.indent(full_sitemap, space='  ')
    ET.ElementTree(full_sitemap).write(OUTPUT / 'sitemap.xml', encoding='utf-8', xml_declaration=True)

    sitemap = ET.Element('{' + namespace + '}urlset')
    entries = [(BASE + '/aktuelles/', max((post['modified'] for post in posts), default='2026-10-12'))]
    entries += [(url(post), post['modified']) for post in posts]
    for address, modified in entries:
        entry = ET.SubElement(sitemap, '{' + namespace + '}url')
        ET.SubElement(entry, '{' + namespace + '}loc').text = address
        ET.SubElement(entry, '{' + namespace + '}lastmod').text = modified
    ET.indent(sitemap, space='  ')
    ET.ElementTree(sitemap).write(OUTPUT / 'sitemap-aktuelles.xml', encoding='utf-8', xml_declaration=True)
    rss = ET.Element('rss', version='2.0')
    channel = ET.SubElement(rss, 'channel')
    for key, value in [('title', 'Pinienkaffee – Aktuelles & Artikel'), ('link', BASE + '/aktuelles/'),
                       ('description', 'Neuigkeiten und Artikel von M97 Factory.'), ('language', 'de-DE')]:
        ET.SubElement(channel, key).text = value
    for post in posts:
        item = ET.SubElement(channel, 'item')
        for key, value in [('title', post['title']), ('link', url(post)), ('guid', url(post)),
                           ('description', post['description']), ('pubDate', format_datetime(datetime.fromisoformat(post['published']))),
                           ('category', LABELS[post['category']])]:
            node = ET.SubElement(item, key)
            node.text = value
            if key == 'guid':
                node.set('isPermaLink', 'true')
    ET.indent(rss, space='  ')
    ET.ElementTree(rss).write(NEWS / 'feed.xml', encoding='utf-8', xml_declaration=True)


def main():
    global OUTPUT, NEWS, PREVIEW
    parser = argparse.ArgumentParser()
    parser.add_argument('--preview-output', type=Path, help='Isolated existing site snapshot. Drafts are never written into the live checkout.')
    args = parser.parse_args()
    if args.preview_output:
        OUTPUT = args.preview_output.resolve()
        if OUTPUT == ROOT or ROOT in OUTPUT.parents:
            raise ValueError('Preview must be outside the deployment checkout')
        PREVIEW = True
        NEWS = OUTPUT / 'aktuelles'
    posts = load_posts()
    NEWS.mkdir(exist_ok=True)
    (NEWS / 'index.html').write_text(archive(posts), encoding='utf-8')
    for post in posts:
        directory = OUTPUT / post.get('path', '/aktuelles/' + post['slug'] + '/').lstrip('/')
        directory.mkdir(parents=True, exist_ok=True)
        (directory / 'index.html').write_text(article(post), encoding='utf-8')
    desired = {OUTPUT / post.get('path', '/aktuelles/' + post['slug'] + '/').lstrip('/') / 'index.html' for post in posts}
    previous_pages = list(NEWS.glob('*/index.html')) + list((OUTPUT / 'magazin').glob('*/index.html'))
    for previous in previous_pages:
        generated = previous.read_text(encoding='utf-8')
        if previous not in desired and (MARKER in generated or '<!-- Generated editorial from content/editorial/' in generated):
            previous.unlink()
            if not any(previous.parent.iterdir()):
                previous.parent.rmdir()
    xml_outputs([post for post in posts if post.get('status') != 'draft'])
    homepage = OUTPUT / 'index.html'
    if homepage.is_file():
        existing = homepage.read_text(encoding='utf-8')
        start, end = '<!-- JOURNAL CAROUSEL START -->', '<!-- JOURNAL CAROUSEL END -->'
        if start in existing and end in existing:
            before, remainder = existing.split(start, 1)
            _, after = remainder.split(end, 1)
            homepage.write_text(before + start + '\n' + editorial.home_carousel(posts) + '\n' + end + after, encoding='utf-8')
    google_tags.install(OUTPUT)
    print(f'Built news archive, {len(posts)} articles, RSS, sitemap, journal carousel and Google Ads integration.')


if __name__ == '__main__':
    main()
